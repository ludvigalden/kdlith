//! The consuming workspace's root dependency lines, checked and never
//! written, and the owned `.cargo/config.toml` patching the kdlith git
//! source to a local checkout; both from one named source.

use std::path::Path;

use kdlith_diagnostic::DiagnosticRecord;
use kdlith_engine::{DeclaredSource, DefinitionKind};

use crate::manifest::{DRIFT, UNOWNED, WriteError, record};

/// The owned cargo configuration file, relative to the workspace root.
pub const CARGO_CONFIG: &str = ".cargo/config.toml";

/// The prefix every kdlith comment marker starts with, whatever the
/// version that wrote it: a file whose first line carries it is owned.
const MARKER_PREFIX: &str = "# generated by kdlith ";

const ROOT_DEPENDENCY: &str = "KDLITH-GEN006";
const UNPINNABLE: &str = "KDLITH-GEN007";

/// The kdlith crates a schema reader resolves transitively, by
/// directory under `pkg/rs`. A patch covers exactly these: a missing
/// one resolves twice, an extra one is an unused patch.
const SCHEMA_CLOSURE: [&str; 6] = [
    "diagnostic",
    "engine",
    "model",
    "parse",
    "runtime",
    "superproc",
];

/// The cargo source of the kdlith crates: the git repository and the
/// full commit a named source's origin declares.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct CargoSource {
    pub git: String,
    pub rev: String,
}

/// The cargo source `declared` pins, or the `KDLITH-GEN007` record
/// saying why it cannot: it is not an origin, its `rev` is not a full
/// 40-hex commit, or its `path` is not the repository root.
pub fn cargo_source(
    name: &str,
    declared: &DeclaredSource,
) -> Result<CargoSource, Box<DiagnosticRecord>> {
    let refuse = |reason: String| Box::new(record(UNPINNABLE, &[name, &reason]));
    let Some(origin) = &declared.origin else {
        return Err(refuse(format!(
            "it is declared as a {} source, not an origin with git= and rev=",
            declared.kind
        )));
    };
    let rev = match origin.rev.as_deref() {
        None => return Err(refuse("its origin declares no rev=".to_owned())),
        Some(rev) if !is_full_commit(rev) => {
            return Err(refuse(format!(
                "its origin rev={rev} is not a full commit (40 lowercase hex digits)"
            )));
        }
        Some(rev) => rev.to_owned(),
    };
    if let Some(path) = origin.path.as_deref().filter(|path| !path.is_empty()) {
        return Err(refuse(format!(
            "its origin path={path} is not the repository root"
        )));
    }
    Ok(CargoSource {
        git: origin.git.clone(),
        rev,
    })
}

fn is_full_commit(rev: &str) -> bool {
    rev.len() == 40 && rev.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

/// The kdlith crates a schema-reader patch covers, as package names.
pub fn patch_crates() -> impl Iterator<Item = String> {
    SCHEMA_CLOSURE.iter().map(|dir| format!("kdlith-{dir}"))
}

/// The root `[workspace.dependencies]` lines a generated schema reader
/// needs, in manifest order, each spelled exactly as the check expects.
pub fn workspace_dependencies(source: &CargoSource) -> Vec<String> {
    crate::dependency_dirs(DefinitionKind::Schema)
        .into_iter()
        .map(|dir| {
            format!(
                "kdlith-{dir} = {{ git = {}, rev = {} }}",
                quoted(&source.git),
                quoted(&source.rev)
            )
        })
        .collect()
}

/// Check `<root>/Cargo.toml` against [`workspace_dependencies`], line
/// by line and never writing it: one `KDLITH-GEN006` per crate whose
/// line is missing, different, or local (a path or `[patch]` entry).
pub fn check_workspace(
    root: &Path,
    source: &CargoSource,
) -> Result<Vec<DiagnosticRecord>, WriteError> {
    let file = root.join("Cargo.toml");
    let text = std::fs::read_to_string(&file).map_err(|source| WriteError::Io {
        path: file.clone(),
        source,
    })?;
    let shown = file.display().to_string();
    let mut found: Vec<(String, Entry)> = Vec::new();
    let mut table = String::new();
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            table = trimmed
                .trim_start_matches('[')
                .split(']')
                .next()
                .unwrap_or("")
                .trim()
                .to_owned();
            if let Some(name) = table.strip_prefix("workspace.dependencies.") {
                found.push((unquote(name).to_owned(), Entry::Different));
            }
            continue;
        }
        let Some(key) = line_key(trimmed) else {
            continue;
        };
        if !key.starts_with("kdlith-") {
            continue;
        }
        let entry = if table.starts_with("patch.") || table == "patch" {
            Entry::Local
        } else if table == "workspace.dependencies" {
            if has_path_key(trimmed) {
                Entry::Local
            } else {
                Entry::Line(line.trim_end().to_owned())
            }
        } else {
            continue;
        };
        found.push((key.to_owned(), entry));
    }
    let mut findings = Vec::new();
    for (dir, expected) in crate::dependency_dirs(DefinitionKind::Schema)
        .into_iter()
        .zip(workspace_dependencies(source))
    {
        let name = format!("kdlith-{dir}");
        let entries: Vec<&Entry> = found
            .iter()
            .filter(|(key, _)| *key == name)
            .map(|(_, entry)| entry)
            .collect();
        let state = if entries.iter().any(|entry| matches!(entry, Entry::Local)) {
            Some("local")
        } else if entries.is_empty() {
            Some("missing")
        } else if entries.len() == 1 && matches!(entries[0], Entry::Line(line) if *line == expected)
        {
            None
        } else {
            Some("different")
        };
        if let Some(state) = state {
            findings.push(record(ROOT_DEPENDENCY, &[&name, &shown, state, &expected]));
        }
    }
    Ok(findings)
}

/// What one manifest line says about a kdlith crate.
enum Entry {
    /// A `[workspace.dependencies]` line, as written.
    Line(String),
    /// A path dependency or a `[patch]` entry.
    Local,
    /// A dotted table or another spelling the check does not accept.
    Different,
}

/// The bare key a `key = value` or `key.sub = value` line assigns.
fn line_key(line: &str) -> Option<&str> {
    if line.starts_with('#') {
        return None;
    }
    let (key, _) = line.split_once('=')?;
    let key = key.split('.').next()?.trim();
    Some(unquote(key))
}

fn unquote(key: &str) -> &str {
    let key = key.trim();
    key.strip_prefix('"')
        .and_then(|k| k.strip_suffix('"'))
        .or_else(|| key.strip_prefix('\'').and_then(|k| k.strip_suffix('\'')))
        .unwrap_or(key)
}

fn has_path_key(line: &str) -> bool {
    let Some((key, value)) = line.split_once('=') else {
        return false;
    };
    key.trim_end().ends_with(".path")
        || value
            .trim()
            .strip_prefix('{')
            .is_some_and(|table| table.split(',').any(|pair| pair.trim().starts_with("path")))
}

/// The owned `.cargo/config.toml`: the kdlith marker, then, given a
/// checkout, a `[patch."<git>"]` pointing the closure at
/// `<checkout>/pkg/rs`; without one, the marker alone keeps it owned.
pub fn cargo_patch(source: &CargoSource, checkout: Option<&Path>) -> Result<String, WriteError> {
    let mut text = format!("{}\n", crate::COMMENT_MARKER);
    let Some(checkout) = checkout else {
        return Ok(text);
    };
    let Some(dir) = checkout.to_str() else {
        return Err(WriteError::Io {
            path: checkout.to_owned(),
            source: std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                "the checkout path is not UTF-8, so cargo cannot be pointed at it",
            ),
        });
    };
    text.push('\n');
    text.push_str(&format!("[patch.{}]\n", quoted(&source.git)));
    for crate_dir in SCHEMA_CLOSURE {
        let path = format!("{dir}/pkg/rs/{crate_dir}");
        text.push_str(&format!(
            "kdlith-{crate_dir} = {{ path = {} }}\n",
            quoted(&path)
        ));
    }
    Ok(text)
}

/// Whether the existing file's first line is a kdlith comment marker.
fn owned(text: &str) -> bool {
    text.lines()
        .next()
        .is_some_and(|line| line.starts_with(MARKER_PREFIX))
}

/// Write `content` to `<root>/.cargo/config.toml`: an existing file
/// whose first line is not a kdlith marker refuses with
/// `KDLITH-GEN001` and stays unchanged.
pub fn write_patch(root: &Path, content: &str) -> Result<(), WriteError> {
    let target = root.join(CARGO_CONFIG);
    match std::fs::read_to_string(&target) {
        Ok(existing) if !owned(&existing) => {
            let shown = target.display().to_string();
            return Err(WriteError::Refused(vec![record(UNOWNED, &[&shown])]));
        }
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(source) => {
            return Err(WriteError::Io {
                path: target,
                source,
            });
        }
    }
    if let Some(parent) = target.parent() {
        std::fs::create_dir_all(parent).map_err(|source| WriteError::Io {
            path: parent.to_owned(),
            source,
        })?;
    }
    std::fs::write(&target, content).map_err(|source| WriteError::Io {
        path: target,
        source,
    })
}

/// Compare `<root>/.cargo/config.toml` with `content` without writing:
/// absent is *missing*, a file without the marker *unowned*, a patch
/// where none is expected *stale*, and any other difference *changed*,
/// each one `KDLITH-GEN002` record.
pub fn check_patch(root: &Path, content: &str) -> Result<Vec<DiagnosticRecord>, WriteError> {
    let target = root.join(CARGO_CONFIG);
    let shown = target.display().to_string();
    let state = match std::fs::read_to_string(&target) {
        Ok(existing) if existing == content => return Ok(Vec::new()),
        Ok(existing) if !owned(&existing) => "unowned",
        Ok(existing) if existing.contains("[patch") && !content.contains("[patch") => "stale",
        Ok(_) => "changed",
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => "missing",
        Err(source) => {
            return Err(WriteError::Io {
                path: target,
                source,
            });
        }
    };
    Ok(vec![record(DRIFT, &[&shown, state])])
}

/// The one-time seed for an empty cargo git cache while the origin is
/// unreachable: the git command line fetches the pinned revision from
/// `checkout` in place of `source.git`, scoped to one cargo run.
pub fn seed_recipe(source: &CargoSource, checkout: &Path) -> String {
    format!(
        "GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=url.{}.insteadOf GIT_CONFIG_VALUE_0={} \
         CARGO_NET_GIT_FETCH_WITH_CLI=true cargo generate-lockfile",
        checkout.display(),
        source.git
    )
}

/// A TOML basic string.
fn quoted(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", u32::from(c))),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
